CREATE TABLE IF NOT EXISTS ab_leads (
 id CHAR(32) PRIMARY KEY,
 tenant_id CHAR(32) NOT NULL,
 service_id CHAR(32) NULL,
 service_name VARCHAR(120) NOT NULL DEFAULT '',
 customer_name VARCHAR(120) NOT NULL,
 customer_email VARCHAR(190) NOT NULL,
 customer_phone VARCHAR(40) NOT NULL DEFAULT '',
 customer_address VARCHAR(250) NOT NULL DEFAULT '',
 customer_notes TEXT NOT NULL,
 internal_notes TEXT NOT NULL,
 stage VARCHAR(16) NOT NULL DEFAULT 'new',
 booking_id CHAR(32) NULL,
 source VARCHAR(100) NOT NULL DEFAULT 'website',
 campaign VARCHAR(150) NOT NULL DEFAULT '',
 marketing_consent TINYINT NOT NULL DEFAULT 0,
 request_key VARCHAR(64) NOT NULL,
 request_hash CHAR(64) NOT NULL,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT ab_lead_tenant FOREIGN KEY (tenant_id) REFERENCES ab_tenants(id),
 CONSTRAINT ab_lead_service FOREIGN KEY (service_id) REFERENCES ab_services(id),
 CONSTRAINT ab_lead_booking FOREIGN KEY (booking_id) REFERENCES ab_bookings(id),
 UNIQUE KEY ab_lead_request(tenant_id,request_key),
 UNIQUE KEY ab_lead_booking_unique(booking_id),
 INDEX ab_lead_created(tenant_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
